//! Nginx vhost template per project. PHP is served by the FPM container of the chosen version.

use crate::config::php_container;
use crate::projects::{self, Project};

pub fn render_vhost(p: &Project, with_ssl: bool) -> String {
    let root = if p.docroot.is_empty() {
        projects::container_dir(p)
    } else {
        format!("{}/{}", projects::container_dir(p), p.docroot)
    };
    let php = php_container(&p.php_version);
    // Variable + resolver: nginx starts even when a PHP container is not running yet.
    let location = format!(
        r#"    root {root};
    index index.php index.html;
    client_max_body_size 128m;
    resolver 127.0.0.11 valid=10s ipv6=off;

    location / {{
        try_files $uri $uri/ /index.php?$query_string;
    }}

    location ~ \.php$ {{
        include fastcgi_params;
        set $php_upstream {php}:9000;
        fastcgi_pass $php_upstream;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_read_timeout 300;
    }}

    location ~ /\.(?!well-known) {{
        deny all;
    }}
"#
    );
    if with_ssl {
        format!(
            r#"# Generated by WebDock Dev - do not edit
server {{
    listen 80;
    server_name {d} *.{d};
    return 301 https://$host$request_uri;
}}

server {{
    listen 443 ssl;
    server_name {d} *.{d};
    ssl_certificate     /etc/nginx/certs/{d}.pem;
    ssl_certificate_key /etc/nginx/certs/{d}-key.pem;
{location}}}
"#,
            d = p.domain
        )
    } else {
        format!(
            "# Generated by WebDock Dev - do not edit\nserver {{\n    listen 80;\n    server_name {d} *.{d};\n{location}}}\n",
            d = p.domain
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vhost_points_to_php_container() {
        let p = Project {
            name: "shop".into(),
            domain: "shop.test".into(),
            php_version: "8.3".into(),
            db_name: None,
            docroot: "public".into(),
            ssl: true,
            enabled: true,
            custom_path: None,
        };
        let v = render_vhost(&p, true);
        assert!(v.contains("set $php_upstream ldp-php83:9000"));
        assert!(v.contains("root /var/www/shop/public;"));
        assert!(v.contains("listen 443 ssl"));
        assert!(!render_vhost(&p, false).contains("443"));
    }
}
